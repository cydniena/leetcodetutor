// Exports the seeded learner's analytics to docs/data/analytics.js for the
// GitHub Pages project page. Written as `window.ANALYTICS = {...}` rather than
// a .json file so the page needs no fetch -- it works on Pages and from a
// local file:// open, with no CORS surprises.
//
// Run after seeding:  npm run export:analytics
//
// This is seeded demo data and the page says so plainly. The point of shipping
// it is that the charts are real query output rather than mockups.

import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { pool } from '../src/db.js';
import { todayFor } from '../src/lib/dates.js';
import {
  headlineComparison, hintDependencyByWeek, masteryGrid, planAdherence,
  retentionByGap, timeToSolveByWeek, todayQueue,
} from '../src/repos/analytics.js';

const OUT = join(
  dirname(fileURLToPath(import.meta.url)), '..', '..', 'docs', 'data', 'analytics.js',
);
const DEMO_EMAIL = 'learner@example.com';

async function main() {
  const { rows } = await pool.query(
    'select id, email, timezone from app_user where email = $1', [DEMO_EMAIL],
  );
  if (!rows[0]) throw new Error(`no ${DEMO_EMAIL}; run \`npm run seed\` first`);
  const user = rows[0];
  const today = todayFor(user);

  const [
    mastery, timeToSolve, hintDependency, retention, adherence, queue, headline,
  ] = await Promise.all([
    masteryGrid(pool, user.id),
    timeToSolveByWeek(pool, user.id),
    hintDependencyByWeek(pool, user.id),
    retentionByGap(pool, user.id),
    planAdherence(pool, user.id),
    todayQueue(pool, user.id, today),
    headlineComparison(pool, user.id),
  ]);

  const totals = (await pool.query(
    `select
       (select count(*) from topic)    as topics,
       (select count(*) from pattern)  as patterns,
       (select count(*) from problem)  as problems,
       (select count(*) from pattern_hint) as hints,
       (select count(*) from attempt where user_id = $1) as attempts,
       (select count(*) from attempt where user_id = $1 and is_baseline) as baseline_attempts,
       (select min(attempted_on)::text from attempt where user_id = $1) as first_attempt,
       (select max(attempted_on)::text from attempt where user_id = $1) as last_attempt`,
    [user.id],
  )).rows[0];

  const payload = {
    generated_at: new Date().toISOString(),
    source: 'seeded demo data (server/scripts/seed.js), not a real study history',
    // Exported explicitly: the page cannot derive "today" from the queue,
    // because the newest due row is only today's date if something happens to
    // be due today.
    today,
    timezone: user.timezone,
    totals,
    headline,
    mastery,
    timeToSolve,
    hintDependency,
    retention,
    adherence,
    queue,
  };

  await mkdir(dirname(OUT), { recursive: true });
  await writeFile(
    OUT,
    `// GENERATED by server/scripts/export-analytics.js -- do not edit by hand.\n`
    + `// Regenerate with: npm run export:analytics\n`
    + `window.ANALYTICS = ${JSON.stringify(payload, null, 2)};\n`,
  );

  console.log(`wrote ${OUT}`);
  console.log(`  ${totals.attempts} attempts (${totals.baseline_attempts} baseline), `
    + `${totals.first_attempt} to ${totals.last_attempt}`);
  await pool.end();
}

main().catch(async (err) => {
  console.error(err.message);
  await pool.end();
  process.exit(1);
});
